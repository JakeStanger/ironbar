/// D-Bus representation of [`DeviceType`].
///
/// [`DeviceType`]'s own `Deserialize` impl reads variant names for use in config,
/// whereas D-Bus sends the `u32` discriminant.
#[derive(Clone, Copy, Debug, Deserialize, Type)]
#[serde(from = "u32")]
#[zbus(signature = "u")]
pub struct DbusDeviceType(pub DeviceType);

impl From<u32> for DbusDeviceType {
    fn from(number: u32) -> Self {
        let device_type = match number {
            1 => DeviceType::Ethernet,
            2 => DeviceType::Wifi,
            3 => DeviceType::Unused1,
            4 => DeviceType::Unused2,
            5 => DeviceType::Bt,
            6 => DeviceType::OlpcMesh,
            7 => DeviceType::Wimax,
            8 => DeviceType::Modem,
            9 => DeviceType::Infiniband,
            10 => DeviceType::Bond,
            11 => DeviceType::Vlan,
            12 => DeviceType::Adsl,
            13 => DeviceType::Bridge,
            14 => DeviceType::Generic,
            15 => DeviceType::Team,
            16 => DeviceType::Tun,
            17 => DeviceType::IpTunnel,
            18 => DeviceType::Macvlan,
            19 => DeviceType::Vxlan,
            20 => DeviceType::Veth,
            21 => DeviceType::Macsec,
            22 => DeviceType::Dummy,
            23 => DeviceType::Ppp,
            24 => DeviceType::OvsInterface,
            25 => DeviceType::OvsPort,
            26 => DeviceType::OvsBridge,
            27 => DeviceType::Wpan,
            28 => DeviceType::SixLowpan,
            29 => DeviceType::Wireguard,
            30 => DeviceType::WifiP2p,
            31 => DeviceType::Vrf,
            32 => DeviceType::Loopback,
            33 => DeviceType::Hsr,
            34 => DeviceType::Ipvlan,
            _ => DeviceType::Unknown,
        };

        Self(device_type)
    }
}

/// See: <https://people.freedesktop.org/~lkundrak/nm-docs/nm-dbus-types.html#NMDeviceState>
#[derive(Clone, Copy, Debug, OwnedVariant, PartialEq, Eq, Deserialize, Type)]
#[serde(from = "u32")]
#[repr(u32)]
pub enum DeviceState {
    /// The device's state is unknown
    Unknown = 0,
    /// The device is recognized, but not managed by NetworkManager
    Unmanaged = 10,
    /// The device is managed by NetworkManager, but is not available for use. Reasons may include
    /// the wireless switched off, missing firmware, no ethernet carrier, missing supplicant or
    /// modem manager, etc.
    Unavailable = 20,
    /// The device can be activated, but is currently idle and not connected to a network.
    Disconnected = 30,
    /// The device is preparing the connection to the network. This may include operations like
    /// changing the MAC address, setting physical link properties, and anything else required to
    /// connect to the requested network.
    Prepare = 40,
    /// The device is connecting to the requested network. This may include operations like
    /// associating with the WiFi AP, dialing the modem, connecting to the remote Bluetooth device,
    /// etc.
    Config = 50,
    /// The device requires more information to continue connecting to the requested network. This
    /// includes secrets like WiFi passphrases, login passwords, PIN codes, etc.<LeftMouse>
    NeedAuth = 60,
    /// The device is requesting IPv4 and/or IPv6 addresses and routing information from the
    /// network.
    IpConfig = 70,
    /// The device is checking whether further action is required for the requested network
    /// connection. This may include checking whether only local network access is available,
    /// whether a captive portal is blocking access to the Internet, etc.
    IpCheck = 80,
    /// The device is waiting for a secondary connection (like a VPN) which must activated before
    /// the device can be activated
    Secondaries = 90,
    /// The device has a network connection, either local or global.
    Activated = 100,
    /// T disconnection from the current network connection was requested, and the device is
    /// cleaning up resources used for that connection. The network connection may still be valid.
    Deactivating = 110,
    /// The device failed to connect to the requested network and is cleaning up the connection
    /// request
    Failed = 120,
}

impl From<u32> for DeviceState {
    fn from(number: u32) -> Self {
        match number {
            10 => Self::Unmanaged,
            20 => Self::Unavailable,
            30 => Self::Disconnected,
            40 => Self::Prepare,
            50 => Self::Config,
            60 => Self::NeedAuth,
            70 => Self::IpConfig,
            80 => Self::IpCheck,
            90 => Self::Secondaries,
            100 => Self::Activated,
            110 => Self::Deactivating,
            120 => Self::Failed,
            _ => Self::Unknown,
        }
    }
}
